def _body(markdown: str) -> str:
    from ..bibliography import source_body

    return source_body(markdown)


def _sentences(text: str) -> list[str]:
    parts = re.split(r"(?<=[。！？!?；;])\s*|\n+", text)
    return [p.strip() for p in parts if p.strip()]


def _prose_lines(markdown: str, *, quotes: bool = True, lists: bool = True) -> list[str]:
    """正文段落与列表项的纯文本（去掉标题、代码、表格、公式与图片）。

    ``quotes=False`` 不取引用块（逐字引文）；``lists=False`` 只取正文段落。
    """
    lines: list[str] = []

    def add(inlines: list) -> None:  # type: ignore[type-arg]
        text = plain([inline for inline in inlines if not inline.math and not inline.code])
        if text.strip():
            lines.append(text.strip())

    for block in parse_blocks(_body(markdown)):
        if block.kind == "paragraph" or (quotes and block.kind == "quote"):
            add(block.inlines)
        elif lists and block.kind == "list":
            for item in block.items:
                add(item.inlines)
    return lines


def _short(text: str, limit: int = 40) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[:limit] + "…"


def check_register(markdown: str, policy: QualityPolicy) -> list[Finding]:
    findings: list[Finding] = []
    prose = _prose_lines(markdown)
    for line in prose:
        for sentence in _sentences(line):
            for first, second, label in _PAIRED_FRAMES:
                if first == "既":
                    if _JI_YOU.search(sentence):
                        findings.append(
                            Finding(
                                "paired-frame", "error", f"成对套话「{label}」", _short(sentence)
                            )
                        )
                    continue
                head = sentence.find(first)
                if head >= 0 and sentence.find(second, head + len(first)) > head:
                    findings.append(
                        Finding("paired-frame", "error", f"成对套话「{label}」", _short(sentence))
                    )
                    break
            if len(re.sub(r"\s", "", sentence)) > policy.max_sentence_chars:
                findings.append(
                    Finding(
                        "overlong-sentence",
                        "warning",
                        f"超长句（超过 {policy.max_sentence_chars} 字），建议拆分",
                        _short(sentence),
                    )
                )
        lowered = line.casefold()
        for phrase in _COLLOQUIAL:
            if phrase.casefold() in lowered:
                findings.append(
                    Finding("colloquial", "error", f"口语化或夸张措辞「{phrase}」", _short(line))
                )
        match = _PRODUCTION.search(line)
        if match:
            findings.append(
                Finding(
                    "production-narration",
                    "error",
                    f"正文出现生产过程描述「{match.group(0)}」",
                    _short(line),
                )
            )
        punct = _CJK_ASCII_PUNCT.search(line)
        if punct:
            findings.append(
                Finding(
                    "cjk-ascii-punctuation",
                    "warning",
                    f"中文句中使用了半角标点「{punct.group(0)}」",
                    _short(line),
                )
            )
    # 同一问题在长文里可能命中很多次：按 (code, message) 去重，最多保留 12 条
    unique: dict[tuple[str, str], Finding] = {}
    for item in findings:
        unique.setdefault((item.code, item.message), item)
    return list(unique.values())[:12]


def _unquoted(text: str) -> str:
    return _QUOTED.sub("", text)


def _advice(code: str, message: str, excerpts: list[str]) -> Finding:
    """同一代码只报一条：首处原句作摘录，其余计数。"""
    more = f"（共 {len(excerpts)} 处）" if len(excerpts) > 1 else ""
    return Finding(code, "warning", message + more, _short(excerpts[0]))


def check_phrasing(markdown: str) -> list[Finding]:
    """模板化语体。只作建议：单个连接词或评价词并不错，密集、机械地出现才需要改写。"""
    hits: dict[str, list[str]] = {}
    labels: dict[str, str] = {}

    def hit(code: str, label: str, sentence: str) -> None:
        hits.setdefault(code, []).append(sentence)
        labels.setdefault(code, label)

    sentences = [s for line in _prose_lines(markdown, quotes=False) for s in _sentences(line)]
    for sentence in sentences:
        text = _unquoted(sentence)
        shell = next((phrase for phrase in _EMPTY_SHELLS if phrase in text), None)
        if shell:
            hit("empty-phrase", shell, sentence)
        for code, pattern in (
            ("vague-evaluation", _VAGUE_EVALUATION),
            ("reader-directive", _READER_DIRECTIVE),
        ):
            match = pattern.search(text)
            if match:
                hit(code, match.group(0), sentence)
    findings = [
        _advice(code, message.format(labels[code]), hits[code])
        for code, message in (
            ("empty-phrase", "空壳句式「{}」：删去后直接陈述其后的实质命题"),
            ("vague-evaluation", "空洞评价「{}」：改为具体的对象、数值、比较或明确的限制"),
            ("reader-directive", "读者指令「{}」：直接报告事实、推导或图表引用"),
        )
        if code in hits
    ]

    paragraphs = _prose_lines(markdown, quotes=False, lists=False)
    openers = [p for p in paragraphs if _STACKED_OPENER.match(_unquoted(p))]
    if len(paragraphs) >= 5 and len(openers) >= 3 and len(openers) * 10 >= len(paragraphs) * 3:
        findings.append(
            _advice(
                "connective-stacking",
                f"{len(openers)}/{len(paragraphs)} 段以「首先」「此外」「最后」等连接词起句，"
                "请按实际的因果、转折或条件关系衔接",
                openers[:1],
            )
        )
    selves = [s for s in sentences if _SELF_REFERENCE.match(s)]
    if len(selves) >= 5 and len(selves) * 10 >= len(sentences):
        findings.append(
            _advice(
                "self-reference-density",
                f"{len(selves)} 句以「本文」「我们」等自指起句，请让研究对象、方法或证据作主语",
                selves[:1],
            )
        )
    dashed = [s for s in sentences if "——" in _unquoted(s)]
    dashes = sum(_unquoted(s).count("——") for s in sentences)
    if dashes >= 4 and dashes * 400 >= sum(len(s) for s in sentences):
        findings.append(
            _advice(
                "dash-density",
                f"长破折号「——」出现 {dashes} 次，主张与解释、因果或列举请改用明确的连词或标点",
                dashed[:1],
            )
        )
    return findings


def check_claims(markdown: str) -> list[Finding]:
    """比较、显著性、优先权与「证明」类措辞须有数值、检验或来源撑着。只作建议。"""
    hits: dict[str, list[str]] = {}
    for line in _prose_lines(markdown, quotes=False):
        for sentence in _sentences(line):
            text = _unquoted(sentence)
            cited = bool(_CITE.search(text))
            attributed = bool(_ATTRIBUTED.search(text))
            checks = (
                (
                    "unquantified-superiority",
                    bool(_SUPERIORITY.search(text))
                    and not re.search(r"\d", _CITE_OR_YEAR.sub("", text)),
                ),
                (
                    "significance-without-test",
                    bool(_SIGNIFICANCE.search(text)) and not _STAT_ANCHOR.search(text),
                ),
                (
                    "unattributed-novelty",
                    bool(_NOVELTY.search(text)) and not (cited or attributed),
                ),
                ("proof-overclaim", bool(_PROOF.search(text)) and not attributed),
                ("generic-attribution", bool(_GENERIC_ATTRIBUTION.search(text)) and not cited),
            )
            for code, matched in checks:
                if matched:
                    hits.setdefault(code, []).append(sentence)
    return [
        _advice(code, _CLAIM_MESSAGES[code], hits[code])
        for code in _CLAIM_MESSAGES
        if code in hits
    ]


def _sections(markdown: str) -> list[tuple[str, str]]:
    """(二级标题, 该节正文) 列表。"""
    parts = re.split(r"(?m)^##\s+(.+?)\s*$", _body(markdown))
    return [(parts[i].strip(), parts[i + 1]) for i in range(1, len(parts) - 1, 2)]


_TRANSLATION_TITLE = re.compile(r"翻译|译文|translation", re.I)
_REPEAT_MIN_CHARS = 30


def _fingerprint(sentence: str) -> str:
    """句子主干：去掉引号内原文、引用角标、空白与标点。"""
    return re.sub(r"\W", "", _CITE.sub("", _unquoted(sentence))).casefold()


def check_repetition(markdown: str) -> list[Finding]:
    """同一句话写了两遍：每个论点只在一处展开。只作建议。

    比对句子主干，较短的一句整体出现在另一句里也算；译文节逐句对应原文，不参与比对。
    """
    seen: list[tuple[str, str]] = []
    pairs: list[tuple[str, str, str]] = []
    for title, text in _sections(markdown):
        if _TRANSLATION_TITLE.search(title):
            continue
        for line in _prose_lines(text, quotes=False):
            for sentence in _sentences(line):
                key = _fingerprint(sentence)
                if len(key) < _REPEAT_MIN_CHARS:
                    continue
                home = next(
                    (at for seen_key, at in seen if key in seen_key or seen_key in key), None
                )
                if home is None:
                    seen.append((key, title))
                else:
                    pairs.append((home, title, sentence))
    if not pairs:
        return []
    first, second, _ = pairs[0]
    where = f"「{first}」节内" if first == second else f"「{first}」与「{second}」"
    return [
        _advice(
            "repeated-sentence",
            f"同一句话在{where}重复出现；每个论点只在一处展开，其他位置改为概括或删去",
            [sentence for _, _, sentence in pairs],
        )
    ]


def check_abstract(markdown: str) -> list[Finding]:
    for title, text in _sections(markdown):
        if any(key in title.casefold() for key in _ABSTRACT_TITLES):
            if _CITE.search(citation_text(text)):
                return [
                    Finding(
                        "abstract-citation",
                        "error",
                        f"「{title}」中出现引用角标；摘要应能脱离正文独立阅读，来源归属放到正文",
                    )
                ]
    return []


def check_clusters(markdown: str, policy: QualityPolicy) -> list[Finding]:
    worst = 0
    example = ""
    for match in _CITE.finditer(citation_text(_body(markdown))):
        size = len(re.split(r"\s*[,，]\s*", match.group(1)))
        if size > worst:
            worst, example = size, match.group(0)
    if worst > policy.max_citation_cluster:
        return [
            Finding(
                "citation-cluster",
                "error",
                f"单处并列 {worst} 个引用（上限 {policy.max_citation_cluster}），"
                "请拆分论断并说明每个来源各自支撑什么",
                example,
            )
        ]
    return []


def _normalize_url(url: str) -> str:
    from ..bibliography import document_identity

    identity, _ = document_identity(url)
    identity = re.sub(r"^(arxiv:.+?)v\d+$", r"\1", identity)
    return re.sub(r"^https?://(www\.)?", "", identity, flags=re.I).rstrip("/")


def source_counts(
    citations: list[str],
    references: dict[str, str] | None = None,
    *,
    document_keys: dict[str, str] | None = None,
) -> tuple[int, list[str]]:
    # Display titles are not identities: distinct uploads commonly share a filename.
    # Distinct locations/URLs of one work are valid citations; only literally
    # repeated URL entries are duplicates. Both still count as one research work.
    seen: set[str] = set()
    urls: set[str] = set()
    duplicates: list[str] = []
    for url in citations:
        seen.add(_normalize_url((document_keys or {}).get(url) or url))
        if url in urls:
            duplicates.append(url)
        urls.add(url)
    return len(seen), duplicates


def check_sources(
    citations: list[str],
    used: int,
    minimum: int,
    *,
    references: dict[str, str] | None = None,
    document_keys: dict[str, str] | None = None,
) -> list[Finding]:
    findings: list[Finding] = []
    unique, duplicates = source_counts(citations, references, document_keys=document_keys)
    if duplicates:
        findings.append(
            Finding(
                "duplicate-source",
                "error",
                f"引用列表中 {len(duplicates)} 处重复登记了相同来源链接",
                _short(duplicates[0], 60),
            )
        )
    distinct = max(0, used - (len(citations) - unique))
    if minimum and distinct < minimum:
        findings.append(
            Finding(
                "citation-shortfall",
                "error",
                f"正文实际引用 {distinct} 个不同的已核验来源，少于下限 {minimum} 个",
            )
        )
    return findings


def requested_year(query: str) -> int | None:
    """任务文本里点名的起始年份（「2025 年以来」「since 2024」「2024–2026」）。"""
    for pattern in (_YEAR_REQUEST, _SINCE_EN):
        match = pattern.search(query)
        if match:
            return int(match.group(1))
    return None


def check_recency(query: str, source_texts: list[str]) -> list[Finding]:
    year = requested_year(query)
    if year is None:
        return []
    hits = sum(1 for text in source_texts if any(int(y) >= year for y in _YEAR_ANY.findall(text)))
    if hits == 0:
        return [
            Finding(
                "recency-gap",
                "error",
                f"任务要求 {year} 年及之后的文献，但已核验来源中找不到该时段的文献",
            )
        ]
    return []


def check_limitations(markdown: str) -> list[Finding]:
    body = _body(markdown).casefold()
    if any(word in body for word in _LIMITATION_WORDS):
        return []
    return [
        Finding(
            "missing-limitations",
            "error",
            "没有说明局限、不确定性或未解决的问题；科研交付物必须写明结论的边界",
        )
    ]


def uncited_sections_for(scratch: dict[str, object]) -> tuple[str, ...]:
    """从黑板上的任务契约推出不带引用的章节（无契约的普通研究为空）。"""
    from .contract import contract_from_scratch
    from .quality import coerce_policy

    contract = contract_from_scratch(scratch)  # type: ignore[arg-type]
    if contract is None:
        return ()
    return abstract_sections(contract.template, coerce_policy(contract.quality))


def abstract_sections(template_key: str, policy: QualityPolicy) -> tuple[str, ...]:
    """按规范不带引用角标的章节标题关键词（交给引用复核豁免「必须引用」）。"""
    if policy.forbid_abstract_citations and template_key in _ABSTRACT_TEMPLATES:
        return _ABSTRACT_TITLES
    return ()


_LIMITATION_TEMPLATES = {"litReview", "autoResearch", "paperRead", "peerReview"}
_ABSTRACT_TEMPLATES = {"litReview", "autoResearch", "paperRead"}
_REGISTER_TEMPLATES = {"litReview", "autoResearch", "paperRead", "peerReview", "dataAnalysis"}


def writing_rules(template_key: str) -> str:
    """写作提示里的表述要求。与建议级检查共用同一份词表：写作时先避开，检查只兜底。"""
    if template_key not in _REGISTER_TEMPLATES:
        return ""
    shells = "」「".join(_EMPTY_SHELLS[:6])
    return (
        f"表述要求：直接陈述内容，不用「{shells}」等空壳句式；"
        "不写「具有重要意义」「提供了新的思路」「应用前景广阔」这类没有内容的评价，"
        "改为写明具体作用、条件或数值；不用「读者可以看到」等读者指令；"
        "段首不机械堆叠「首先」「此外」「最后」，不连续以「本文」「我们」起句，少用破折号插入说明。"
        "比较优劣写出指标数值、数据集或设置；「显著」只用于给出统计检验或区间的结果；"
        "「首次」类说法须有来源，或写明是作者的说法；实验与数据结果写「表明」「支持」，不写「证明」；"
        "「已有研究表明」须紧跟具体引用。同一论点只在一处展开，其他位置概括或省略，不整句重复。"
        "引文与译文忠实于原文，不按以上要求改写。"
    )


def evaluate(
    markdown: str,
    *,
    template_key: str,
    query: str,
    citations: list[str],
    used_citations: int,
    min_citations: int,
    policy: QualityPolicy,
    source_texts: list[str] | None = None,
    references: dict[str, str] | None = None,
    document_keys: dict[str, str] | None = None,
) -> ScholarlyReport:
    """对一篇定稿跑全部学术检查；按任务类型与策略开关决定跑哪些。"""
    report = ScholarlyReport()
    if policy.register_check and template_key in _REGISTER_TEMPLATES:
        report.findings += check_register(markdown, policy)
        report.findings += check_phrasing(markdown)
        report.findings += check_claims(markdown)
        report.findings += check_repetition(markdown)
    if policy.forbid_abstract_citations and template_key in _ABSTRACT_TEMPLATES:
        report.findings += check_abstract(markdown)
    if citations:
        report.findings += check_clusters(markdown, policy)
    report.findings += check_sources(
        citations, used_citations, min_citations, references=references, document_keys=document_keys
    )
    if policy.recency_check and source_texts is not None:
        report.findings += check_recency(query, source_texts)
    if policy.require_limitations and template_key in _LIMITATION_TEMPLATES:
        report.findings += check_limitations(markdown)
    report.metrics = {
        "errors": len(report.errors),
        "warnings": len(report.warnings),
        "citations_used": source_counts(citations, references, document_keys=document_keys)[0],
        "citation_anchors_used": used_citations,
        "citations_required": min_citations,
    }
    return report


def revision_brief(report: ScholarlyReport, extra: list[str] | None = None) -> str:
    """把检查结果写成交给写作者的返工说明。"""
    items = [f"- {finding.render()}" for finding in report.errors]
    items += [f"- （建议）{finding.render()}" for finding in report.warnings[:5]]
    items += [f"- {line}" for line in extra or []]
    return (
        "上一版未通过交付质量检查，请在保持全部引用角标与数值忠实于素材的前提下修订全文，"
        "逐条解决以下问题；素材确实无法支持的内容，删除或明确标注「素材未覆盖」，"
        "不得为凑数引入素材外的文献或事实：\n" + "\n".join(items)
    )


